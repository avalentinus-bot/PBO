    private void jTable2MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable2MouseClicked
        int baris = jTable2.getSelectedRow();
        
        if (baris != -1) {
            //Mengambil data dari tabel dan memasukkan ke Text Field
            nim.setText(jTable2.getValueAt(baris, 1).toString());
            nama.setText(jTable2.getValueAt(baris, 2).toString());
            nUTS.setText(jTable2.getValueAt(baris, 3).toString());
            nUAS.setText(jTable2.getValueAt(baris, 4).toString());
            nTUGAS.setText(jTable2.getValueAt(baris, 5).toString());
            
            //OPTIMASI: Otomatis menghitung ulang Nilai Akhir & Predikat saat di-klik
            prosesActionPerformed(null);
        }
    }//GEN-LAST:event_jTable2MouseClicked

