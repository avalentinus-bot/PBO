        ps.setString(3, nUTS.getText());
        ps.setString(4, nUAS.getText());
        ps.setString(5, nTUGAS.getText());
        ps.setString(6, nakhir.getText());
        ps.setString(7, nhuruf.getText());
        ps.setString(8, predikat.getText());
