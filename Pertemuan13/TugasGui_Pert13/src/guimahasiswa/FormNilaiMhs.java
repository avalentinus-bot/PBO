    private void tampilkanDiTabel() {
        if (modelTabel != null && con != null) {
            modelTabel.setRowCount(0); 
            try {
                Statement st = con.createStatement();
                ResultSet rs = st.executeQuery("SELECT * FROM mhs");
                int no = 1;
                while(rs.next()) {
                    Object[] baris = {
                        no++,
                        rs.getString("nim"), rs.getString("nama"),
                        rs.getDouble("nilai_uts"), rs.getDouble("nilai_uas"), rs.getDouble("nilai_tugas"),
                        rs.getDouble("nilai_akhir"), rs.getString("nilai_huruf"), rs.getString("predikat")
                    };
                    modelTabel.addRow(baris);
                }
            } catch (SQLException e) {
                e.printStackTrace();
            }
        }
    }

    private void refreshUI() {
        kosongkanTextField();
        tampilkanDiTabel();
    }
