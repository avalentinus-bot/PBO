    private void hapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_hapusActionPerformed
int konfirmasi = JOptionPane.showConfirmDialog(this, "Yakin hapus?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
    if (konfirmasi == JOptionPane.YES_OPTION) {
        try {
            PreparedStatement ps = con.prepareStatement("DELETE FROM mhs WHERE nim = ?");
            ps.setString(1, nim.getText());
            ps.executeUpdate();
            refreshUI();
        } catch (SQLException ex) {}
    }
    }//GEN-LAST:event_hapusActionPerformed

    private void updateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateActionPerformed
try {
        PreparedStatement ps = con.prepareStatement("UPDATE mhs SET nama=?, nilai_uts=?, nilai_uas=?, nilai_tugas=?, nilai_akhir=?, nilai_huruf=?, predikat=? WHERE nim=?");
        ps.setString(1, nama.getText());
        ps.setString(2, nUTS.getText());
        ps.setString(3, nUAS.getText());
        ps.setString(4, nTUGAS.getText());
        ps.setString(5, nakhir.getText());
        ps.setString(6, nhuruf.getText());
        ps.setString(7, predikat.getText());
        ps.setString(8, nim.getText()); 
        ps.executeUpdate();

        JOptionPane.showMessageDialog(this, "Data berhasil diupdate!");
        refreshUI(); 
    } catch(SQLException ex) {
        JOptionPane.showMessageDialog(this, "Gagal Update Data!");
    }
    }//GEN-LAST:event_updateActionPerformed

