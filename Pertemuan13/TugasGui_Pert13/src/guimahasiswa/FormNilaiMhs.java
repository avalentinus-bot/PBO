    private void prosesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_prosesActionPerformed
try {
        String ni = nim.getText();
        String na = nama.getText();
        double ts = Double.parseDouble(nUTS.getText());
        double as = Double.parseDouble(nUAS.getText());
        double tgs = Double.parseDouble(nTUGAS.getText());

        Mhs m = new Mhs(ni, na, ts, as, tgs);

        uts35.setText(String.valueOf(Math.round(m.uts() * 10.0) / 10.0));
        uas35.setText(String.valueOf(Math.round(m.uas() * 10.0) / 10.0));
        tugas30.setText(String.valueOf(Math.round(m.tugas() * 10.0) / 10.0));
        nakhir.setText(String.valueOf(Math.round(m.nilaiAkhir() * 10.0) / 10.0));
        nhuruf.setText(m.getNilHuruf(m.nilaiAkhir()));
        predikat.setText(m.getPredikat(m.getNilHuruf(m.nilaiAkhir())));

    } catch(NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Harap isi angka!");
    }
    }//GEN-LAST:event_prosesActionPerformed

